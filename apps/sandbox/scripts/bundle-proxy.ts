// Bundles src/proxy.ts (browser code) into a string constant module. Used by scripts/build.ts and by
// the freshness test, so the checked in src/generated/proxy-script.ts can never drift from its source.

import { build } from 'esbuild';
import { dirname, join } from 'node:path';

export const SANDBOX_ROOT = join(dirname(new URL(import.meta.url).pathname), '..');
export const GENERATED_PATH = join(SANDBOX_ROOT, 'src', 'generated', 'proxy-script.ts');

export async function bundleProxy(): Promise<string> {
  const result = await build({
    entryPoints: [join(SANDBOX_ROOT, 'src', 'proxy.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
  });
  const js = result.outputFiles[0]?.text ?? '';
  return js.replace(/<\/script/gi, '<\\/script').trim();
}

export function generatedModule(js: string): string {
  return [
    '// Generated by scripts/build.ts from src/proxy.ts. Do not edit; run `npm run build -w @fixwright/sandbox`.',
    `export const PROXY_SCRIPT = ${JSON.stringify(js)};`,
    '',
  ].join('\n');
}
