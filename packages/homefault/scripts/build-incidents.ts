// Rebuilds incidents/*.json and src/incidents.ts from scripts/incidents.ts. Every file is validated
// and evidence-checked before anything is written. Run: npm run incidents

import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { checkEvidence } from '../src/scenario/evidence.ts';
import { validateScenario } from '../src/scenario/validate.ts';
import { buildIncident } from './incident-kit.ts';
import { INCIDENT_SPECS } from './incidents.ts';

const dir = new URL('../incidents/', import.meta.url);
const scenarios = INCIDENT_SPECS.map(buildIncident);

const problems: string[] = [];
for (const s of scenarios) {
  const v = validateScenario(s);
  if (!v.ok) problems.push(`${s.id}: ${v.errors.join('; ')}`);
  const e = checkEvidence(s);
  if (!e.supported) problems.push(`${s.id}: evidence ${[...e.missing, ...e.contradictions].join('; ')}`);
}
if (new Set(scenarios.map((s) => s.id)).size !== scenarios.length) problems.push('duplicate incident ids');
if (problems.length > 0) {
  console.error(problems.join('\n'));
  process.exit(1);
}

mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) if (f.endsWith('.json')) rmSync(new URL(f, dir));
for (const s of scenarios) {
  writeFileSync(new URL(`${s.id}.json`, dir), `${JSON.stringify({ $schema: '../schema/scenario.schema.json', ...s }, null, 2)}\n`);
}

const names = scenarios.map((s, i) => ({ id: s.id, ident: `inc${String(i + 1).padStart(2, '0')}` }));
const module = `// Generated by scripts/build-incidents.ts from scripts/incidents.ts. Do not edit by hand.
// The 20 incident scenarios, reconstructed from dated public reports (see each file's source and assumptions).

import { parseScenario } from './scenario/validate.ts';
import type { Scenario } from './scenario/types.ts';
${names.map((n) => `import ${n.ident} from '../incidents/${n.id}.json' with { type: 'json' };`).join('\n')}

const RAW: readonly unknown[] = [${names.map((n) => n.ident).join(', ')}];

export const INCIDENT_IDS: readonly string[] = [${names.map((n) => `'${n.id}'`).join(', ')}];

let cache: Scenario[] | undefined;

/** All incidents, validated on first use. */
export function loadIncidents(): Scenario[] {
  cache ??= RAW.map((raw) => {
    const { $schema: _schema, ...rest } = raw as Record<string, unknown>;
    return parseScenario(rest);
  });
  return cache;
}
`;
writeFileSync(new URL('../src/incidents.ts', import.meta.url), module);
console.log(`wrote ${scenarios.length} incidents`);
for (const s of scenarios) console.log(`  ${s.id}  ${s.ground_truth.cause_id}  ${s.source.date}  ${s.events.length} rows`);
